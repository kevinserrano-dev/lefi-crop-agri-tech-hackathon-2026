def test_a_refused_device_is_told_why() -> None:
    """ADR-056: revoked by someone, replaced by a newer pairing of the same PC, or expired."""
    from dataclasses import replace as dc_replace
    from datetime import UTC, datetime
    from uuid import uuid4

    from lefi_brain.modules.client_devices.api import revoked_details
    from lefi_brain.modules.client_devices.domain import (
        REPLACED_REASON,
        ClientDevice,
        DeviceStatus,
    )

    at = datetime(2026, 11, 8, tzinfo=UTC)
    device = ClientDevice(
        id=uuid4(),
        name="TEST desk",
        platform="macos",
        fingerprint="ab" * 32,
        serial="01",
        issued_at=at,
        expires_at=at,
        status=DeviceStatus.ACTIVE,
        paired_ip=None,
    )
    assert revoked_details(device)["reason"] == "expired"
    revoked = dc_replace(device, status=DeviceStatus.REVOKED, revoked_at=at, revoked_reason="x")
    assert revoked_details(revoked)["reason"] == "revoked"
    replaced = dc_replace(revoked, revoked_reason=REPLACED_REASON)
    assert revoked_details(replaced)["reason"] == "replaced"
