async def paired_fingerprint(app: FastAPI) -> tuple[str, str]:
    code = (await service(app).new_code(Actor.system())).code
    async with http(app) as c:
        body = (await pair(c, code, device_csr())).json()
    der = x509.load_pem_x509_certificate(body["cert_pem"].encode()).public_bytes(
        serialization.Encoding.DER
    )
    return body["device_id"], sha256_hex(der)


async def test_through_the_gateway_only_a_paired_device_gets_in(
    app: FastAPI, paired_settings: Settings
) -> None:
    device_id, fp = await paired_fingerprint(app)
    login = {"username": "admin", "password": ADMIN_PW}
    async with http(app) as c:
        assert (await c.get("/api/v1/health", headers=GATEWAY)).status_code == 200
        no_cert = await c.post("/api/v1/auth/login", json=login, headers=GATEWAY)
        assert (no_cert.status_code, no_cert.json()["error"]["code"]) == (401, "DEVICE_NOT_PAIRED")
        # Why (ADR-056): the gateway sent no certificate, or one Lefi Brain does not know.
        assert no_cert.json()["error"]["details"] == {"reason": "no_certificate"}
        # Caddy forwards the SHA-256 of nothing when the client sent no certificate.
        empty = {**GATEWAY, "X-Client-Cert-Fingerprint": EMPTY_SHA256}
        res = await c.post("/api/v1/auth/login", json=login, headers=empty)
        assert res.json()["error"]["details"] == {"reason": "no_certificate"}
        unknown = {**GATEWAY, "X-Client-Cert-Fingerprint": "ab" * 32}
        res = await c.post("/api/v1/auth/login", json=login, headers=unknown)
        assert res.status_code == 401
        assert res.json()["error"]["details"] == {"reason": "unknown_certificate"}
        with_cert = {**GATEWAY, "X-Client-Cert-Fingerprint": fp.upper()}
        ok = await c.post("/api/v1/auth/login", json=login, headers=with_cert)
        assert ok.status_code == 200, ok.text
        # Local tools on this PC (no gateway in between) are not asked for a device.
        assert (await c.post("/api/v1/auth/login", json=login)).status_code == 200

    # The sign-in is audited with the device next to the user (ADR-022).
    path = sqlite_path(paired_settings.resolved_database_url)
    assert path is not None
    rows = sqlite3.connect(path).execute(
        "SELECT client_device_id FROM audit_log WHERE action = 'auth.login' ORDER BY seq"
    )
    assert [r[0] for r in rows] == [device_id, None]
    log = (paired_settings.log_dir / "brain-access.log").read_text().splitlines()
    assert any(json.loads(line)["device_id"] == device_id for line in log)

    # From another machine the header is not believed, and nothing but health/pair answers.
    async with http(app, peer="192.0.2.77") as other:
        forged = {"X-Client-Cert-Fingerprint": fp}
        res = await other.post("/api/v1/auth/login", json=login, headers=forged)
        assert res.status_code == 401
        assert res.json()["error"]["details"] == {"reason": "not_through_gateway"}
        assert (await other.get("/api/v1/health")).status_code == 200


async def test_a_revoked_device_is_refused_at_once(app: FastAPI) -> None:
    device_id, fp = await paired_fingerprint(app)
    headers = {**GATEWAY, "X-Client-Cert-Fingerprint": fp}
    login = {"username": "admin", "password": ADMIN_PW}
    async with http(app) as c:
        assert (await c.post("/api/v1/auth/login", json=login, headers=headers)).status_code == 200
        from uuid import UUID

        await service(app).revoke(UUID(device_id), Actor.system(), "lost laptop")
        res = await c.get("/api/v1/auth/session", headers=headers)
        assert (res.status_code, res.json()["error"]["code"]) == (401, "DEVICE_REVOKED")
        details = res.json()["error"]["details"]
        assert (details["reason"], details["device_id"]) == ("revoked", device_id)
        assert details["revoked_reason"] == "lost laptop"
        assert (await c.get("/api/v1/health", headers=headers)).status_code == 200


