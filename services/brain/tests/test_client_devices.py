ADMIN_PW = "first-admin-pass-1"  # TEST ONLY


def _name(cn: str) -> x509.Name:
    return x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, cn)])


def fake_root(now_dt: object) -> tuple[ec.EllipticCurvePrivateKey, x509.Certificate]:
    """A stand-in for Lefi Crop Helper's LEFI root CA (TEST ONLY)."""
    from datetime import datetime

    assert isinstance(now_dt, datetime)
    key = ec.generate_private_key(ec.SECP256R1())
    cert = (
        x509.CertificateBuilder()
        .subject_name(_name("TEST ONLY fake LEFI root"))
        .issuer_name(_name("TEST ONLY fake LEFI root"))
        .public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now_dt - timedelta(days=1))
        .not_valid_after(now_dt + timedelta(days=3650))
        .add_extension(x509.BasicConstraints(ca=True, path_length=1), critical=True)
        .sign(key, hashes.SHA256())
    )
    return key, cert


def sign_issuing(
    csr_pem: str, root_key: ec.EllipticCurvePrivateKey, root: x509.Certificate, now_dt: object
) -> bytes:
    from datetime import datetime

    assert isinstance(now_dt, datetime)
    csr = x509.load_pem_x509_csr(csr_pem.encode())
    cert = (
        x509.CertificateBuilder()
        .subject_name(csr.subject)
        .issuer_name(root.subject)
        .public_key(csr.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now_dt - timedelta(minutes=1))
        .not_valid_after(now_dt + timedelta(days=5 * 365))
        .add_extension(x509.BasicConstraints(ca=True, path_length=0), critical=True)
        .sign(root_key, hashes.SHA256())
    )
    return cert.public_bytes(serialization.Encoding.PEM)


def device_csr(key: object | None = None) -> tuple[str, bytes]:
    key = key or ec.generate_private_key(ec.SECP256R1())
    csr = (
        x509.CertificateSigningRequestBuilder()
        .subject_name(_name("TEST ONLY desktop"))
        .sign(key, hashes.SHA256())  # type: ignore[arg-type]
    )
    return csr.public_bytes(serialization.Encoding.PEM).decode(), csr.public_bytes(
        serialization.Encoding.DER
    )


