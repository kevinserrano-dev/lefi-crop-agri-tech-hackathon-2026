def test_the_issuing_ca_is_checked_before_install(tmp_path: Path, clock: FakeClock) -> None:
    ca = FileCa(tmp_path / "ca")
    csr = ca.request()
    assert (tmp_path / "ca" / "issuing.key").stat().st_mode & 0o777 == 0o600
    assert (tmp_path / "ca").stat().st_mode & 0o777 == 0o700
    root_key, root = fake_root(clock.now())
    _, other_root = fake_root(clock.now())
    signed = sign_issuing(csr, root_key, root, clock.now())
    other_pem = other_root.public_bytes(serialization.Encoding.PEM)
    from lefi_brain.modules.client_devices.domain import CaNotReadyError

    with pytest.raises(CaNotReadyError, match="not signed by that root"):
        ca.install(signed, other_pem, clock.now())
    foreign = sign_issuing(FileCa(tmp_path / "other").request(), root_key, root, clock.now())
    root_pem = root.public_bytes(serialization.Encoding.PEM)
    with pytest.raises(CaNotReadyError, match="not for this Brain"):
        ca.install(foreign, root_pem, clock.now())
    ca.install(signed, root_pem, clock.now())
    status = ca.status()
    assert status["ready"] and status["two_level"]


