def http(app: FastAPI, peer: str = "127.0.0.1") -> httpx.AsyncClient:
    transport = httpx.ASGITransport(app=app, client=(peer, 50000))
    return httpx.AsyncClient(transport=transport, base_url="http://brain.test")


def service(app: FastAPI) -> ClientDeviceService:
    s: ClientDeviceService = app.state.client_devices
    return s


GATEWAY = {"X-Forwarded-For": "192.0.2.50", "X-Forwarded-Proto": "https"}


async def pair(
    client: httpx.AsyncClient,
    code: str,
    csr: tuple[str, bytes],
    machine_id: str | None = None,
) -> httpx.Response:
    key = proof_key(normalise_code(code) or "")
    body = {
        "csr_pem": csr[0],
        "proof": request_proof(key, csr[1]),
        "device_name": "TEST desk 1",
        "platform": "macos",
    }
    if machine_id:
        body["machine_id"] = machine_id
    return await client.post("/api/v1/devices/pair", json=body, headers=GATEWAY)


async def test_a_code_pairs_one_device_once(app: FastAPI, gateway_ca: Path) -> None:
    gateway_pem = gateway_ca.read_text()  # noqa: ASYNC240 - small test file
    code = (await service(app).new_code(Actor.system(), "front desk")).code
    assert len(code) == 14 and code.count("-") == 2
    csr = device_csr()
    async with http(app) as c:
        res = await pair(c, code, csr)
        assert res.status_code == 200, res.text
        body = res.json()
        # The answer is bound to the code: the app checks this before pinning anything.
        expected = response_proof(
            proof_key(normalise_code(code) or ""),
            body["device_id"],
            body["cert_pem"],
            body["ca_pem"],
            body["gateway_ca_pem"],
        )
        assert body["proof"] == expected
        assert body["gateway_ca_pem"] == gateway_pem
        cert = x509.load_pem_x509_certificate(body["cert_pem"].encode())
        cn = cert.subject.get_attributes_for_oid(NameOID.COMMON_NAME)[0].value
        assert cn == body["device_id"]
        eku = cert.extensions.get_extension_for_class(x509.ExtendedKeyUsage).value
        assert list(eku) == [ExtendedKeyUsageOID.CLIENT_AUTH]
        assert not cert.extensions.get_extension_for_class(x509.BasicConstraints).value.ca
        issuing = x509.load_pem_x509_certificate(body["ca_pem"].encode())  # first in the chain
        cert.verify_directly_issued_by(issuing)
        assert (cert.not_valid_after_utc - cert.not_valid_before_utc).days == 365
        # Single use, whatever the CSR.
        again = await pair(c, code, device_csr())
        assert again.status_code == 403
        assert again.json()["error"]["code"] == "PAIRING_REFUSED"


async def test_pairing_the_same_pc_again_replaces_its_older_pairing(app: FastAPI) -> None:
    """ADR-055: one entry per PC. Another PC (another machine id, or none) is never touched."""
    pc_a, pc_b = "a" * 64, "b" * 64  # TEST ONLY machine ids
    ids: dict[str, str] = {}
    async with http(app) as c:
        for label, mid in (("a1", pc_a), ("b1", pc_b), ("none", None), ("a2", pc_a)):
            code = (await service(app).new_code(Actor.system())).code
            res = await pair(c, code, device_csr(), mid)
            assert res.status_code == 200, res.text
            ids[label] = res.json()["device_id"]
        bad = await pair(c, (await service(app).new_code(Actor.system())).code, device_csr(), "x")
        assert bad.status_code == 422
    status = {str(d.id): d for d in await service(app).list()}
    assert status[ids["a1"]].status.value == "revoked"
    assert status[ids["a1"]].revoked_reason == "replaced by a new pairing of this PC"
    assert status[ids["a2"]].status.value == "active"
    assert status[ids["a2"]].machine_id == pc_a
    assert status[ids["b1"]].status.value == "active"
    assert status[ids["none"]].status.value == "active"


async def test_wrong_and_expired_codes_get_the_same_answer(app: FastAPI, clock: FakeClock) -> None:
    code = (await service(app).new_code(Actor.system())).code
